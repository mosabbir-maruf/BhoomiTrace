/**
 * Source documents: the evidence that extracted values point back to.
 *
 * ## Access
 *
 * A document has an owner. An applicant may only see and change their own
 * documents; a document belonging to somebody else is reported as *not found*,
 * so an identifier cannot be used to probe for other people's filings.
 * Reviewers and admins may read every document, because review work requires
 * following the evidence; only the owner or an admin may change metadata.
 *
 * ## Storage
 *
 * A stored file is identified internally by `storage_key`, which is generated by
 * the server. That key is **never** returned in an API response: a caller does
 * not need it and cannot influence it. Downloads go through an endpoint that
 * re-checks access first. `original_filename` is kept purely for display and is
 * never used as a path component.
 *
 * ## Retention
 *
 * Documents are not deleted through the API. `extractions.source_document_id` is
 * `ON DELETE RESTRICT`, so a document that any extraction depends on cannot be
 * removed at all; a document with no dependants can only be retired by status.
 * Registering a document that duplicates an existing checksum is allowed — the
 * same record legitimately appears in more than one filing — but the caller is
 * told, so a genuine duplicate is visible rather than hidden.
 */

export interface DocumentPageView {
  id: string
  pageNumber: number
  label: string | null
  width: number | null
  height: number | null
  /** Present only when a provider actually reported a region. */
  region: BoundingBox | null
}

export function toDocumentPageView(page: DocumentPage): DocumentPageView {
  return {
    id: page.id,
    pageNumber: page.pageNumber,
    label: page.label,
    width: page.width,
    height: page.height,
    region: page.region ?? null,
  }
}

export interface DocumentView {
  id: string
  ownerId: string | null
  origin: 'synthetic_demo' | 'user_created'
  title: string
  kind: SourceDocumentKind
  reference: string | null
  pageCount: number | null
  checksumSha256: string | null
  status: DocumentStatus
  contentType: string | null
  byteSize: number | null
  originalFilename: string | null
  /** Whether a stored file exists. The storage key itself is never exposed. */
  hasStoredFile: boolean
  version: number
  createdAt: string
  updatedAt: string
}

export function toDocumentView(document: SourceDocument): DocumentView {
  return {
    id: document.id,
    ownerId: document.ownerId,
    origin: document.origin,
    title: document.title,
    kind: document.kind,
    reference: document.reference,
    pageCount: document.pageCount,
    checksumSha256: document.checksumSha256,
    status: document.status,
    contentType: document.contentType,
    byteSize: document.byteSize,
    originalFilename: document.originalFilename,
    hasStoredFile: document.storageKey !== null,
    version: document.version,
    createdAt: document.createdAt.toISOString(),
    updatedAt: document.updatedAt.toISOString(),
  }
}

/** The `WHERE` clause an applicant's visibility requires. */
function ownershipFilter(user: User): SQL | undefined {
  return user.role === 'applicant' ? eq(sourceDocuments.ownerId, user.id) : undefined
}

export interface DocumentFilters {
  status?: DocumentStatus
  kind?: SourceDocumentKind
  reference?: string
  title?: string
  origin?: 'synthetic_demo' | 'user_created'
}

/** Lists documents the user may see, newest first. */
export async function listDocuments(
  database: Database,
  input: {
    user: User
    filters: DocumentFilters
    pagination: PaginationQuery
  },
): Promise<Page<DocumentView>> {
  const conditions: (SQL | undefined)[] = [ownershipFilter(input.user)]

  if (input.filters.status !== undefined) {
    conditions.push(eq(sourceDocuments.status, input.filters.status))
  }
  if (input.filters.kind !== undefined) {
    conditions.push(eq(sourceDocuments.kind, input.filters.kind))
  }
  if (input.filters.reference !== undefined) {
    conditions.push(ilike(sourceDocuments.reference, `%${input.filters.reference}%`))
  }
  if (input.filters.title !== undefined) {
    conditions.push(ilike(sourceDocuments.title, `%${input.filters.title}%`))
  }
  if (input.filters.origin !== undefined) {
    conditions.push(eq(sourceDocuments.origin, input.filters.origin))
  }

  const where = and(...conditions.filter((entry): entry is SQL => entry !== undefined))

  const [rows, counted] = await Promise.all([
    database.orm
      .select()
      .from(sourceDocuments)
      .where(where)
      .orderBy(desc(sourceDocuments.createdAt), desc(sourceDocuments.id))
      .limit(input.pagination.limit)
      .offset(input.pagination.offset),
    database.orm
      .select({ count: sql<number>`count(*)::int` })
      .from(sourceDocuments)
      .where(where),
  ])

  return pageOf(
    rows.map(toDocumentView),
    counted[0]?.count ?? 0,
    input.pagination,
  )
}

/**
 * Loads a document the user is allowed to see.
 *
 * @throws {NotFoundError} when it does not exist or is not visible — the two
 *   cases are indistinguishable on purpose.
 */
export async function loadVisibleDocument(
  database: Database,
  user: User,
  documentId: string,
): Promise<SourceDocument> {
  const rows = await database.orm
    .select()
    .from(sourceDocuments)
    .where(and(eq(sourceDocuments.id, documentId), ownershipFilter(user)))
    .limit(1)

  const document = rows[0]
  if (document === undefined) {
    throw new NotFoundError('No source document exists with that identifier.')
  }
  return document
}

/** Rejects a metadata change by anybody other than the owner or an admin. */
function assertCanChangeDocument(user: User, document: SourceDocument): void {
  if (user.role === 'admin') return
  if (document.ownerId !== user.id) {
    throw new ForbiddenError('You do not own this source document.')
  }
}

export interface RegisterDocumentInput {
  user: User
  title: string
  kind: SourceDocumentKind
  reference?: string | null
  pageCount?: number | null
  status?: DocumentStatus
  ownerId?: string | null
  requestId?: string | null
  /** Page references to record alongside the document, when already known. */
  pages?: readonly {
    pageNumber: number
    label?: string | null
    width?: number | null
    height?: number | null
    region?: BoundingBox | null
  }[]
}

/**
 * Registers a document that has no stored file.
 *
 * This is the manual-entry path: a record the reviewer has in front of them but
 * which the platform does not hold a scan of. It is a first-class case — an
 * extraction may have no source document at all — so this is not a degraded
 * mode, and the resulting document is simply one with `hasStoredFile: false`.
 */
export async function registerDocument(
  database: Database,
  input: RegisterDocumentInput,
): Promise<DocumentView> {
  const ownerId =
    input.user.role === 'admin' ? (input.ownerId ?? input.user.id) : input.user.id

  // Only an administrator can reach this with somebody else's identifier, and
  // an identifier that names no account is a bad request rather than a
  // dependency problem, so it is answered like one.
  if (input.user.role === 'admin' && input.ownerId !== undefined) {
    await requireExistingUser(database, ownerId)
  }

  return database.orm.transaction(async (tx) => {
    const inserted = await tx
      .insert(sourceDocuments)
      .values({
        ownerId,
        origin: 'user_created',
        title: input.title.trim(),
        kind: input.kind,
        reference: input.reference ?? null,
        pageCount: input.pageCount ?? null,
        status: input.status ?? 'submitted',
        createdBy: input.user.id,
      })
      .returning()

    const document = inserted[0]
    if (document === undefined) {
      throw new Error('Document insert did not return the created row.')
    }

    if (input.pages !== undefined && input.pages.length > 0) {
      const seen = new Set<number>()
      for (const page of input.pages) {
        if (page.pageNumber < 1) {
          throw new BadRequestError('Page numbers start at 1.')
        }
        if (seen.has(page.pageNumber)) {
          throw new ConflictError(`Page ${page.pageNumber} was supplied twice.`)
        }
        seen.add(page.pageNumber)
      }

      await tx.insert(documentPages).values(
        input.pages.map((page) => ({
          sourceDocumentId: document.id,
          pageNumber: page.pageNumber,
          label: page.label ?? null,
          width: page.width ?? null,
          height: page.height ?? null,
          region: page.region ?? null,
        })),
      )
    }

    await recordAuditEvent(tx, {
      actor: { kind: 'user', userId: input.user.id, role: input.user.role },
      action: AuditActions.documentRegistered,
      entityType: 'source_document',
      entityId: document.id,
      summary: 'Source document registered (no stored file).',
      changes: {
        title: document.title,
        kind: document.kind,
        reference: document.reference,
        pageCount: document.pageCount,
        storedFile: false,
      },
      requestId: input.requestId ?? null,
    })

    return toDocumentView(document)
  })
}

export interface RegisterUploadInput {
  user: User
  uploadDir: string
  maxBytes: number
  stream: Readable
  /** Display-only client filename. Never used to build a path. */
  filename?: string | null
  title: string
  kind: SourceDocumentKind
  reference?: string | null
  status?: DocumentStatus
  requestId?: string | null
  /** Forwards the transport's truncation flag; see `StoreUploadOptions`. */
  isTruncated?: () => boolean
}

/**
 * Streams an uploaded file into private storage and registers it.
 *
 * Order matters: the file is written first so its checksum and size are known,
 * and the database row is written second. If the row cannot be written, the
 * file is removed, so a failed request never leaves an orphan behind.
 */
export async function registerUploadedDocument(
  database: Database,
  input: RegisterUploadInput,
): Promise<DocumentView> {
  const stored = await storeUploadedStream(input.stream, {
    uploadDir: input.uploadDir,
    maxBytes: input.maxBytes,
    ...(input.isTruncated === undefined ? {} : { isTruncated: input.isTruncated }),
  })

  try {
    return await database.orm.transaction(async (tx) => {
      const inserted = await tx
        .insert(sourceDocuments)
        .values({
          ownerId: input.user.id,
          origin: 'user_created',
          title: input.title.trim(),
          kind: input.kind,
          reference: input.reference ?? null,
          status: input.status ?? 'submitted',
          storageKey: stored.storageKey,
          originalFilename: input.filename?.slice(0, 255) ?? null,
          contentType: stored.contentType,
          byteSize: stored.byteSize,
          checksumSha256: stored.checksumSha256,
          createdBy: input.user.id,
        })
        .returning()

      const document = inserted[0]
      if (document === undefined) {
        throw new Error('Document insert did not return the created row.')
      }

      await recordAuditEvent(tx, {
        actor: { kind: 'user', userId: input.user.id, role: input.user.role },
        action: AuditActions.documentRegistered,
        entityType: 'source_document',
        entityId: document.id,
        summary: 'Source document uploaded.',
        changes: {
          title: document.title,
          kind: document.kind,
          byteSize: document.byteSize,
          contentType: document.contentType,
          checksumSha256: document.checksumSha256,
          // The filename is echoed only as a display string.
          originalFilename: document.originalFilename,
        },
        requestId: input.requestId ?? null,
      })

      return toDocumentView(document)
    })
  } catch (error) {
    // Compensating action: the database has no record of this file, so it must
    // not remain on disk.
    await removeStoredFile(uploadDirectory(input.uploadDir), stored.storageKey)
    throw error
  }
}

export interface UpdateDocumentInput {
  user: User
  documentId: string
  version: number
  title?: string
  reference?: string | null
  pageCount?: number | null
  status?: DocumentStatus
  requestId?: string | null
}

/** Updates document metadata under optimistic concurrency control. */
export async function updateDocument(
  database: Database,
  input: UpdateDocumentInput,
): Promise<DocumentView> {
  const existing = await loadVisibleDocument(database, input.user, input.documentId)
  assertCanChangeDocument(input.user, existing)

  return database.orm.transaction(async (tx) => {
    const updated = await tx
      .update(sourceDocuments)
      .set({
        ...(input.title === undefined ? {} : { title: input.title.trim() }),
        ...(input.reference === undefined ? {} : { reference: input.reference }),
        ...(input.pageCount === undefined ? {} : { pageCount: input.pageCount }),
        ...(input.status === undefined ? {} : { status: input.status }),
      })
      .where(
        and(
          eq(sourceDocuments.id, input.documentId),
          eq(sourceDocuments.version, input.version),
        ),
      )
      .returning()

    const document = updated[0]
    if (document === undefined) {
      throw new ConcurrencyError(
        'This document was changed by somebody else. Reload it and try again.',
      )
    }

    await recordAuditEvent(tx, {
      actor: { kind: 'user', userId: input.user.id, role: input.user.role },
      action: AuditActions.documentMetadataUpdated,
      entityType: 'source_document',
      entityId: document.id,
      summary: 'Source document metadata updated.',
      changes: {
        before: {
          title: existing.title,
          reference: existing.reference,
          pageCount: existing.pageCount,
          status: existing.status,
          version: existing.version,
        },
        after: {
          title: document.title,
          reference: document.reference,
          pageCount: document.pageCount,
          status: document.status,
          version: document.version,
        },
      },
      requestId: input.requestId ?? null,
    })

    return toDocumentView(document)
  })
}

/** Lists a visible document's pages in page order. */
export async function listDocumentPages(
  database: Database,
  user: User,
  documentId: string,
): Promise<DocumentPageView[]> {
  await loadVisibleDocument(database, user, documentId)

  const rows = await database.orm
    .select()
    .from(documentPages)
    .where(eq(documentPages.sourceDocumentId, documentId))
    .orderBy(asc(documentPages.pageNumber))

  return rows.map(toDocumentPageView)
}

export interface AddPageInput {
  user: User
  documentId: string
  pageNumber: number
  label?: string | null
  width?: number | null
  height?: number | null
  /** Only ever supplied from a provider's own output. */
  region?: BoundingBox | null
  requestId?: string | null
}

/**
 * Adds a page reference to a document.
 *
 * The service records what it is given and nothing more. It does not estimate a
 * bounding box, and it does not guess a page count, because an invented
 * reference would look like evidence.
 */
export async function addDocumentPage(
  database: Database,
  input: AddPageInput,
): Promise<DocumentPageView> {
  const document = await loadVisibleDocument(database, input.user, input.documentId)
  assertCanChangeDocument(input.user, document)

  if (input.pageNumber < 1) {
    throw new BadRequestError('Page numbers start at 1.')
  }

  return database.orm.transaction(async (tx) => {
    const inserted = await tx
      .insert(documentPages)
      .values({
        sourceDocumentId: input.documentId,
        pageNumber: input.pageNumber,
        label: input.label ?? null,
        width: input.width ?? null,
        height: input.height ?? null,
        region: input.region ?? null,
      })
      .returning()

    const page = inserted[0]
    if (page === undefined) {
      throw new Error('Page insert did not return the created row.')
    }

    await recordAuditEvent(tx, {
      actor: { kind: 'user', userId: input.user.id, role: input.user.role },
      action: AuditActions.documentMetadataUpdated,
      entityType: 'document_page',
      entityId: page.id,
      summary: `Page ${page.pageNumber} recorded for source document.`,
      changes: {
        sourceDocumentId: input.documentId,
        pageNumber: page.pageNumber,
        hasRegion: page.region !== null && page.region !== undefined,
      },
      requestId: input.requestId ?? null,
    })

    return toDocumentPageView(page)
  })
}

/**
 * Opens a document's stored file for download.
 *
 * Access is checked before the file is touched. The returned stream is the raw
 * stored bytes; the caller never learns the storage key.
 */
export async function openDocumentFile(
  database: Database,
  user: User,
  documentId: string,
  uploadDir: string,
): Promise<{ stream: Readable; document: SourceDocument }> {
  const document = await loadVisibleDocument(database, user, documentId)

  if (document.storageKey === null) {
    throw new NotFoundError('This source document has no stored file.')
  }

  return {
    stream: openStoredFile(uploadDir, document.storageKey),
    document,
  }
}

/** Computes the SHA-256 of a document's contents without storing it. */
export function checksumOf(contents: string | Buffer): string {
  return sha256Hex(contents)
}
