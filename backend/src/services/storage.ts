import { createHash, randomUUID } from 'node:crypto'
import { createReadStream, createWriteStream } from 'node:fs'
import { mkdir, rm, stat } from 'node:fs/promises'
import { basename, resolve, sep } from 'node:path'
import type { Readable } from 'node:stream'
import { Transform } from 'node:stream'
import { pipeline } from 'node:stream/promises'

import { PayloadTooLargeError, UnsupportedMediaTypeError } from '../lib/errors.js'

/**
 * Private local storage for uploaded evidence.
 *
 * Design constraints, in order of importance:
 *
 * - **Nothing is buffered whole.** An upload is streamed straight to disk while
 *   a running byte count and SHA-256 digest are maintained. A caller cannot make
 *   the process allocate memory proportional to the file size, and an oversized
 *   upload is stopped mid-stream rather than after it has been received.
 * - **The filename is ours, not the caller's.** The storage key is a generated
 *   UUID with no extension. A client-supplied name is never used to build a
 *   path, so `../../etc/passwd` is not a path, it is just a display string.
 * - **The type is sniffed, not asserted.** The declared content type is not
 *   trusted; the first bytes have to look like a PDF, PNG, or JPEG.
 * - **The directory is private.** It is never served statically, and `UPLOAD_DIR`
 *   sits outside any public directory and is Git-ignored.
 *
 * These are local-filesystem semantics. Object storage would replace this module
 * and nothing else; that is deliberately out of scope for this phase.
 */

export type DetectedFileType = 'pdf' | 'png' | 'jpeg'

const SIGNATURES: readonly { type: DetectedFileType; bytes: readonly number[] }[] = [
  { type: 'pdf', bytes: [0x25, 0x50, 0x44, 0x46, 0x2d] }, // %PDF-
  { type: 'png', bytes: [0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a] },
  { type: 'jpeg', bytes: [0xff, 0xd8, 0xff] },
]

/** Content types matching the signatures above. */
export const CONTENT_TYPES: Readonly<Record<DetectedFileType, string>> = {
  pdf: 'application/pdf',
  png: 'image/png',
  jpeg: 'image/jpeg',
}

/** Human-readable list used in error messages and docs. */
export const ALLOWED_UPLOAD_DESCRIPTION = 'PDF, PNG, or JPEG'

/** Identifies a file from its leading bytes, or `null` when unrecognised. */
export function detectFileType(header: Buffer): DetectedFileType | null {
  for (const signature of SIGNATURES) {
    if (header.length < signature.bytes.length) continue
    const matches = signature.bytes.every((byte, index) => header[index] === byte)
    if (matches) return signature.type
  }
  return null
}

/** Absolute path of the private upload directory. */
export function uploadDirectory(uploadDir: string): string {
  return resolve(uploadDir)
}

/**
 * Resolves a storage key to an absolute path, refusing anything that escapes.
 *
 * The key is generated by this module, so this is a defence-in-depth check
 * rather than the primary control: if a key ever contained a separator or `..`,
 * the write or read is refused outright instead of touching an unexpected file.
 */
export function resolveStoragePath(uploadDir: string, storageKey: string): string {
  const directory = uploadDirectory(uploadDir)
  const candidate = resolve(directory, storageKey)

  const isInsideDirectory =
    candidate.startsWith(`${directory}${sep}`) && basename(candidate) === storageKey

  if (!isInsideDirectory) {
    throw new UnsupportedMediaTypeError('The stored file reference is not valid.')
  }

  return candidate
}

export interface StoredFile {
  storageKey: string
  byteSize: number
  checksumSha256: string
  detectedType: DetectedFileType
  contentType: string
}

export interface StoreUploadOptions {
  uploadDir: string
  maxBytes: number
  /**
   * Reports whether the source stopped the stream at its own limit.
   *
   * The multipart layer caps a file at `fileSize` and marks the stream truncated
   * rather than raising, so a file at the boundary arrives as a complete, valid,
   * *short* file. Without this signal an over-limit upload would be stored
   * looking like a legitimate one; the flag is what distinguishes "this file is
   * this size" from "this file was cut off".
   */
  isTruncated?: () => boolean
}

/**
 * Streams an upload into private storage.
 *
 * The file is written under a generated key. If the size limit is exceeded, the
 * type is not recognised, or the stream errors, the partial file is removed
 * before the error propagates — a failed upload leaves nothing behind.
 */
export async function storeUploadedStream(
  stream: Readable,
  options: StoreUploadOptions,
): Promise<StoredFile> {
  const directory = uploadDirectory(options.uploadDir)
  await mkdir(directory, { recursive: true })

  const storageKey = randomUUID()
  const destination = resolveStoragePath(directory, storageKey)

  const hash = createHash('sha256')
  let byteSize = 0
  let header = Buffer.alloc(0)
  let detectedType: DetectedFileType | null = null

  const inspector = new Transform({
    transform(chunk: Buffer, _encoding, callback) {
      byteSize += chunk.length

      if (byteSize > options.maxBytes) {
        callback(
          new PayloadTooLargeError(
            `The file exceeds the ${options.maxBytes} byte limit.`,
          ),
        )
        return
      }

      if (header.length < 8) {
        header = Buffer.concat([header, chunk.subarray(0, 8 - header.length)])
      }

      if (detectedType === null && header.length >= 3) {
        const candidate = detectFileType(header)
        // A 3-byte prefix can only be judged once enough of it has arrived; the
        // shortest signature (JPEG) is 3 bytes, so test them all now.
        if (
          header.length >= 5 ||
          candidate === 'jpeg' ||
          (candidate === null && header.length >= 8)
        ) {
          if (candidate === null) {
            callback(
              new UnsupportedMediaTypeError(
                `Only ${ALLOWED_UPLOAD_DESCRIPTION} files are accepted.`,
              ),
            )
            return
          }
          detectedType = candidate
        }
      }

      hash.update(chunk)
      callback(null, chunk)
    },
  })

  try {
    await pipeline(
      stream,
      inspector,
      // `wx` fails if the generated name already exists, rather than silently
      // overwriting another upload.
      createWriteStream(destination, { flags: 'wx' }),
    )
  } catch (error) {
    await rm(destination, { force: true }).catch(() => undefined)
    throw error
  }

  // Checked before the type test: a file that was cut off is too large whatever
  // its first bytes look like, and that is the more useful thing to report.
  if (options.isTruncated?.() === true) {
    await rm(destination, { force: true }).catch(() => undefined)
    throw new PayloadTooLargeError(
      `The file exceeds the ${options.maxBytes} byte limit.`,
    )
  }

  if (detectedType === null) {
    await rm(destination, { force: true }).catch(() => undefined)
    throw new UnsupportedMediaTypeError(
      `Only ${ALLOWED_UPLOAD_DESCRIPTION} files are accepted.`,
    )
  }

  if (byteSize === 0) {
    await rm(destination, { force: true }).catch(() => undefined)
    throw new UnsupportedMediaTypeError('The uploaded file is empty.')
  }

  const type: DetectedFileType = detectedType
  return {
    storageKey,
    byteSize,
    checksumSha256: hash.digest('hex'),
    detectedType: type,
    contentType: CONTENT_TYPES[type],
  }
}

/** Opens a stored file for reading. Callers must authorise before streaming. */
export function openStoredFile(uploadDir: string, storageKey: string): Readable {
  return createReadStream(resolveStoragePath(uploadDir, storageKey))
}

/** Returns the stored size, or `null` when the file is missing. */
export async function storedFileSize(
  uploadDir: string,
  storageKey: string,
): Promise<number | null> {
  try {
    const info = await stat(resolveStoragePath(uploadDir, storageKey))
    return info.isFile() ? info.size : null
  } catch {
    return null
  }
}

/**
 * Removes a stored file.
 *
 * Used to compensate when the database write that should have described the
 * upload fails, so a rejected request does not leave an orphaned file behind.
 * Never throws: cleanup failing must not replace the original error.
 */
export async function removeStoredFile(
  uploadDir: string,
  storageKey: string,
): Promise<void> {
  await rm(resolveStoragePath(uploadDir, storageKey), { force: true }).catch(
    () => undefined,
  )
}
