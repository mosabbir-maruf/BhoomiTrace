import { randomUUID } from 'node:crypto'

import fastifyCookie from '@fastify/cookie'
import fastifyCors from '@fastify/cors'
import fastifyHelmet from '@fastify/helmet'
import fastifyMultipart from '@fastify/multipart'
import fastifyRateLimit from '@fastify/rate-limit'
import fastifySwagger from '@fastify/swagger'
import fastifySwaggerUi from '@fastify/swagger-ui'
import Fastify, { type FastifyInstance } from 'fastify'
import {
  jsonSchemaTransform,
  serializerCompiler,
  validatorCompiler,
} from 'fastify-type-provider-zod'

import {
  API_PREFIX,
  CSRF_HEADER_NAME,
  SERVICE_VERSION,
  SESSION_COOKIE_NAME,
} from './config/constants.js'
import type { Environment } from './config/env.js'
import { loggerOptions } from './config/logging.js'
import type { Database } from './db/client.js'
import { registerAuthResolution } from './http/auth-context.js'
import { cookieSettingsFromEnvironment } from './http/cookies.js'
import { registerErrorHandling } from './http/errors.js'
import { registerApiRoutes } from './http/routes/index.js'
import { TooManyRequestsError } from './lib/errors.js'
import { healthRoutes } from './routes/health.js'

declare module 'fastify' {
  interface FastifyInstance {
    /** Pooled database client, injected so routes never construct their own. */
    database: Database
    /** Validated configuration, so routes never read `process.env`. */
    appEnv: Environment
  }
}

export interface BuildAppOptions {
  env: Environment
  database: Database
}

/**
 * Largest JSON request body accepted.
 *
 * A JSON body here is a small metadata document; anything approaching a
 * megabyte is not a legitimate request. Evidence files arrive through the
 * multipart upload route, which has its own, separately configured limit and is
 * streamed rather than buffered.
 */
const JSON_BODY_LIMIT_BYTES = 1_048_576

/**
 * Content security policy for the served surface.
 *
 * The API returns JSON, so most directives are about the bundled documentation
 * page. `'unsafe-inline'` is required for script and style because Swagger UI
 * initialises itself with an inline script; the alternative is to drop the CSP
 * on the docs route, which would leave a weaker policy in place than this one.
 * `frame-ancestors 'none'` and `object-src 'none'` are the directives that
 * matter for the API and are enforced on every response.
 */
const CONTENT_SECURITY_POLICY = {
  directives: {
    defaultSrc: ["'self'"],
    baseUri: ["'self'"],
    objectSrc: ["'none'"],
    frameAncestors: ["'none'"],
    formAction: ["'self'"],
    connectSrc: ["'self'"],
    imgSrc: ["'self'", 'data:', 'validator.swagger.io'],
    scriptSrc: ["'self'", "'unsafe-inline'"],
    styleSrc: ["'self'", "'unsafe-inline'"],
  },
}

/** Header a client echoes to prove it can read its own CSRF cookie. */
const BROWSER_REQUEST_HEADERS = ['content-type', CSRF_HEADER_NAME, 'x-request-id']

/**
 * Builds the Fastify application.
 *
 * Construction is separated from listening so that tests can drive the whole
 * stack through `app.inject()` without binding a socket, and so that a
 * misconfiguration surfaces in a test rather than in production.
 *
 * Registration is deliberately lazy — plugins are queued and loaded during
 * `ready()` — but the *order* below is meaningful and must not be rearranged:
 *
 * 1. Type compilers, so every subsequently registered route is validated and
 *    serialised from its Zod schema.
 * 2. The error handler, so a failure inside a plugin is still enveloped.
 * 3. Identity resolution and CSRF/origin guards, as root `onRequest` hooks, so
 *    no route can be added that forgets them.
 * 4. Security headers, CORS, cookies, rate limiting, multipart.
 * 5. The API routes.
 */
export function buildApp(options: BuildAppOptions): FastifyInstance {
  const app = Fastify({
    logger: loggerOptions(options.env),
    // Correlation identifiers are always generated by this process. A
    // client-supplied `x-request-id` is not trusted, because it would let a
    // caller choose what appears in our logs and correlate nothing.
    genReqId: () => randomUUID(),
    trustProxy: options.env.TRUST_PROXY,
    bodyLimit: JSON_BODY_LIMIT_BYTES,
  })

  // Zod schemas are the single source of validation *and* serialisation. The
  // serializer drops fields absent from the response schema, which is what
  // keeps `password_hash` and `storage_key` out of payloads even if a service
  // starts returning them.
  app.setValidatorCompiler(validatorCompiler)
  app.setSerializerCompiler(serializerCompiler)

  app.decorate('database', options.database)
  app.decorate('appEnv', options.env)

  registerErrorHandling(app)

  // Every response — success or failure — carries the correlation identifier it
  // was logged under, so a caller can quote it when reporting a problem. The
  // value is always generated in this process (`genReqId`); a client-supplied
  // header is ignored, so the identifier cannot be forged. The CORS
  // configuration exposes this header to the allowed origins.
  app.addHook('onSend', (request, reply, payload, done) => {
    reply.header('x-request-id', request.id)
    done(null, payload)
  })

  app.register(fastifyHelmet, {
    contentSecurityPolicy: CONTENT_SECURITY_POLICY,
  })

  app.register(fastifyCors, {
    // An explicit list, never `true` or `*`: reflecting an arbitrary origin
    // while sending credentials is the classic CORS misconfiguration.
    origin: options.env.CORS_ALLOWED_ORIGINS,
    credentials: true,
    methods: ['GET', 'POST', 'PATCH', 'PUT', 'DELETE', 'OPTIONS'],
    allowedHeaders: BROWSER_REQUEST_HEADERS,
    exposedHeaders: ['x-request-id'],
    maxAge: 600,
  })

  app.register(fastifyCookie)

  app.register(fastifyRateLimit, {
    // Opt-in per route: only the authentication endpoints are limited now, and
    // a blanket default would silently throttle legitimate bulk reads later.
    global: false,
    // The plugin throws whatever this returns, so returning this API's own
    // error type keeps a throttled response identical in shape to every other
    // failure — same envelope, same stable `rate_limited` code — instead of
    // letting a bare object fall through to the internal-error branch. The
    // plugin sets `retry-after` before throwing, so the wait stays in the
    // response.
    errorResponseBuilder: (_request, context) =>
      new TooManyRequestsError(
        `Too many requests. Try again in ${Math.ceil(context.ttl / 1_000)} second(s).`,
      ),
  })

  app.register(fastifyMultipart, {
    limits: {
      // One small file part and nothing else: metadata travels in the query
      // string, so a body part cannot smuggle unvalidated fields past the
      // request schema.
      fileSize: options.env.UPLOAD_MAX_BYTES,
      files: 1,
      fields: 0,
      parts: 1,
    },
    // The truncation flag is checked explicitly, before anything is written to
    // the database, so the transport must not raise instead: leaving it to the
    // transport would surface the failure *after* the file and its row existed.
    throwFileSizeLimit: false,
  })

  app.register(fastifySwagger, {
    openapi: {
      openapi: '3.0.3',
      info: {
        title: 'BhoomiTrace API',
        version: SERVICE_VERSION,
        description: [
          'Land-record verification and parcel-lineage API.',
          '',
          'Findings produced by this API are **discrepancies to resolve**, not',
          'determinations of fraud. Nothing here decides ownership or marks a',
          'record legally approved.',
          '',
          'Authentication is a server-side session carried in an HTTP-only',
          'cookie. State-changing requests must also present the CSRF token in',
          `the \`${CSRF_HEADER_NAME}\` header, and, when a browser sends one, an`,
          '`Origin` that is on the configured allowlist.',
        ].join('\n'),
      },
      tags: [
        { name: 'auth', description: 'Accounts and sessions' },
        { name: 'parcels', description: 'Parcel records' },
        { name: 'lineage', description: 'Parcel lineage across surveys' },
        { name: 'documents', description: 'Source documents and uploads' },
        { name: 'extractions', description: 'Extracted values and their review' },
        { name: 'review', description: 'Reviewer queue and findings' },
        { name: 'reconciliation', description: 'Deterministic rule evaluation' },
        { name: 'readiness', description: 'Mutation-readiness reports' },
        { name: 'jobs', description: 'Durable background work' },
        { name: 'audit', description: 'Append-only audit trail' },
      ],
      components: {
        securitySchemes: {
          sessionCookie: {
            type: 'apiKey',
            in: 'cookie',
            name: SESSION_COOKIE_NAME,
          },
          csrfToken: {
            type: 'apiKey',
            in: 'header',
            name: CSRF_HEADER_NAME,
          },
        },
      },
    },
    transform: jsonSchemaTransform,
  })

  app.register(fastifySwaggerUi, {
    routePrefix: '/docs',
    uiConfig: {
      docExpansion: 'list',
      deepLinking: true,
    },
  })

  app.register(
    async (api) => {
      // Registered here rather than on the root instance, and after
      // `@fastify/cookie` above, because hooks run in registration order and
      // the first thing the authentication hook does is read a session cookie.
      // `@fastify/cookie` is wrapped in `fastify-plugin`, so its parsing hook
      // attaches to the root instance when the plugin is booted; a hook added
      // to the root *before* boot would run first and see no cookies at all.
      // Scoping these hooks to the API plugin puts them after cookie parsing
      // and confines them to `/api` routes.
      registerAuthResolution(api, {
        settings: cookieSettingsFromEnvironment(options.env),
        allowedOrigins: options.env.CORS_ALLOWED_ORIGINS,
      })

      registerApiRoutes(api)
    },
    { prefix: API_PREFIX },
  )

  // Health endpoints stay outside the versioned prefix: a probe should not have
  // to track the API version.
  app.register(healthRoutes)

  return app
}
